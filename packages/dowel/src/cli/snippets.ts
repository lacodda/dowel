/*
 * Editor snippets for the components a project has copied.
 *
 * Read from `props.json`, the same reading of the components' types the
 * documentation draws its tables from, so a snippet asks for what the
 * component requires - and offers a variant's choices as a list - in the
 * version the project installed. Only the components the project has: a
 * snippet for a component that is not there inserts an import error.
 *
 * VS Code's format: `.vscode/<name>.code-snippets`, a JSON object of snippets,
 * each with a `prefix` typed to call it, a `body` with tab stops (`$1`, a
 * choice as `${1|a,b|}`, `$0` where the cursor ends) and a `description`.
 */

/** A prop as `props.json` records it. */
export interface PropEntry {
  name: string
  type: string
  required?: boolean
  requiredWith?: string[]
  default?: string
  variant?: boolean
  inherited?: boolean
  description?: string
}

/** A component as `props.json` records it. */
export interface ComponentEntry {
  name: string
  description?: string
  is?: Record<string, unknown>
  props?: PropEntry[]
  inherits?: Record<string, unknown>[]
}

export type PropsCatalogue = Record<string, { dir: 'ui' | 'blocks'; components: ComponentEntry[] }>

export interface Snippet {
  prefix: string
  body: string[]
  description: string
  scope: string
}

/** `DatePicker` -> `date-picker`, the way the registry names its files. */
const kebab = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

/** The names of types, which look like words in a union and are not choices. */
const PRIMITIVES = new Set(['string', 'number', 'boolean', 'bigint', 'symbol', 'object', 'unknown', 'any', 'null', 'never'])

/** A union of string literals - `props.json` writes them bare, `sm | md` - as
 * the words to choose from. A type is not a choice: a capital names one
 * (`Date`), and so do the primitives. A choice list's items cannot hold `,`,
 * `|` or `$` unescaped, which plain words never do. */
function choices(type: string): string[] | null {
  const parts = type.split(' | ').map((part) => part.trim())
  return parts.length > 1 && parts.every((part) => /^[a-z][\w-]*$/.test(part) && !PRIMITIVES.has(part))
    ? parts
    : null
}

/** A default as the source writes it - `'md'` - as the word it is. */
const unquoted = (text: string | undefined) => text?.replace(/^['"]|['"]$/g, '')

/** The attribute for one prop, with the tab stop it is given. */
function attribute(prop: PropEntry, stop: number): string {
  const options = choices(prop.type)
  if (options) {
    // The default first, so taking the first choice changes nothing.
    const first = unquoted(prop.default)
    const ordered = first && options.includes(first) ? [first, ...options.filter((o) => o !== first)] : options
    return `${prop.name}="\${${stop}|${ordered.join(',')}|}"`
  }
  if (prop.type === 'string') return `${prop.name}="\${${stop}}"`
  if (prop.type === 'boolean') return prop.name
  return `${prop.name}={\${${stop}}}`
}

/** Whether a component is written with children: one that declares them, or
 * takes the props of an element or a Base UI part, which have them. */
function takesChildren(component: ComponentEntry): boolean {
  if (component.is) return true
  if (component.props?.some((prop) => prop.name === 'children')) return true
  return (component.inherits?.length ?? 0) > 0
}

/** The snippet for one component. */
export function snippetFor(component: ComponentEntry): Snippet {
  const asked = (component.props ?? []).filter(
    (prop) => prop.name !== 'children' && (prop.required === true || prop.variant === true),
  )
  // Required first: they are what the component cannot do without.
  asked.sort((a, b) => Number(b.required === true) - Number(a.required === true))
  const attributes = asked.map((prop, index) => attribute(prop, index + 1))
  const open = [component.name, ...attributes].join(' ')
  const body = takesChildren(component) ? [`<${open}>`, '\t$0', `</${component.name}>`] : [`<${open} />$0`]
  return {
    prefix: `dw-${kebab(component.name)}`,
    body,
    description: component.description ?? component.name,
    scope: 'typescriptreact,javascriptreact',
  }
}

/** Snippets for every component of the items named, keyed by component. */
export function snippetsFor(catalogue: PropsCatalogue, items: readonly string[]): Record<string, Snippet> {
  const snippets: Record<string, Snippet> = {}
  for (const item of [...new Set(items)].sort()) {
    for (const component of catalogue[item]?.components ?? []) snippets[component.name] = snippetFor(component)
  }
  return snippets
}

/** The file, with a word at the top saying where it came from. VS Code reads
 * snippet files as JSON with comments. */
export function snippetsFile(snippets: Record<string, Snippet>, version: string | undefined): string {
  return [
    `// Generated by \`dowel snippets\` from dowel-ui ${version ?? ''}`.trimEnd() + ', for the components this project has copied.',
    '// Run it again after adding a component or upgrading; edits here are overwritten.',
    JSON.stringify(snippets, null, 2),
    '',
  ].join('\n')
}
