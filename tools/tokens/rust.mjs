/*
 * The theme as Rust: `rust/<product>.rs`, one module per product of the line.
 *
 * For a product that draws without CSS - nitid paints its chrome with egui.
 * It used to read the palette and the scales out of the JSON with a build
 * script of its own, which made the Rust shape of the vocabulary nitid's
 * invention: the second native product would have copied the script, and the
 * two copies would have parted at the first rename. Written here, the shape is
 * the theme's, generated from the same model as the JSON beside it.
 *
 * The file names no colour type, because the line's native products need not
 * share a toolkit. It is included into a module that says what a colour is:
 *
 *   mod dowel {
 *       pub type Color = egui::Color32;
 *       const fn rgba(r: u8, g: u8, b: u8, a: u8) -> Color {
 *           egui::Color32::from_rgba_unmultiplied_const(r, g, b, a)
 *       }
 *       include!("../assets/dowel/nitid.rs");
 *   }
 *
 * `Color` has to be `Copy`, `Debug` and `PartialEq`; `[u8; 4]` will do.
 */

/** Rust's reserved words, which a token name could one day be. */
const KEYWORDS = new Set(
  'as async await break const continue crate dyn else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while abstract become box do final macro override priv try typeof unsized virtual yield'.split(
    ' ',
  ),
)

/** `line-2` -> `line_2`: a token as a field. */
export function field(name) {
  const snake = name.replaceAll('-', '_')
  if (!/^[a-z_][a-z0-9_]*$/.test(snake)) throw new Error(`\`--${name}\` cannot be a Rust field`)
  return KEYWORDS.has(snake) ? `r#${snake}` : snake
}

/** `2xl` -> `XXL`, `in-out` -> `IN_OUT`: a step of a scale as a constant. */
export function constant(step) {
  const upper = step.replaceAll('-', '_').toUpperCase()
  const named = upper.replace(/^(\d)([A-Z])/, (_, count, rest) => 'X'.repeat(Number(count)) + rest)
  if (!/^[A-Z][A-Z0-9_]*$/.test(named)) throw new Error(`the step \`${step}\` cannot be a Rust constant`)
  return named
}

/** `#rrggbb` or `#rrggbbaa`, the two forms a palette writes. */
function rgba(hex) {
  const digits = hex.match(/^#([0-9a-f]{6}|[0-9a-f]{8})$/i)?.[1]
  if (!digits) throw new Error(`\`${hex}\` is not #rrggbb or #rrggbbaa`)
  const byte = (at) => Number.parseInt(digits.slice(at, at + 2), 16)
  return [byte(0), byte(2), byte(4), digits.length === 8 ? byte(6) : 255]
}

/** A length in px. A `rem` would need a root size a native window does not
 * have, so it stops the build rather than being guessed. */
function pixels({ value, unit }, where) {
  if (unit !== 'px') throw new Error(`${where} is in ${unit}, and a native product has no root size for it`)
  return value
}

function milliseconds({ value, unit }, where) {
  if (unit === 'ms') return Math.round(value)
  if (unit === 's') return Math.round(value * 1000)
  throw new Error(`${where} is in ${unit}`)
}

const float = (number) => (Number.isInteger(number) ? `${number}.0` : String(number))

/** The steps of a token group, without its `$type` and `$description`. */
const steps = (group) => Object.entries(group).filter(([key]) => !key.startsWith('$'))

/** The palette's modes, as constants: `dark` -> `DARK`. */
const MODES = [
  ['dark', 'DARK', 'The dark theme, as drawn.'],
  ['light', 'LIGHT', 'The light theme, as drawn.'],
  ['dark-contrast-more', 'DARK_CONTRAST_MORE', 'The dark theme when the system asks for more contrast.'],
  ['light-contrast-more', 'LIGHT_CONTRAST_MORE', 'The light theme when the system asks for more contrast.'],
]

/** One product's module. */
export function rustModule({ product, palette, tokens, version }) {
  const { name, accent, colorName } = product
  const modes = MODES.map(([group, constantName, doc]) => {
    const colours = palette.color[group]
    if (!colours) throw new Error(`the ${name} palette has no \`${group}\``)
    return { constantName, doc, colours: Object.entries(colours).map(([token, { $value }]) => [token, rgba($value)]) }
  })
  const names = modes[0].colours.map(([token]) => token)
  for (const mode of modes) {
    const these = mode.colours.map(([token]) => token)
    if (these.join() !== names.join()) {
      throw new Error(`the ${name} palette names different colours in \`${mode.constantName}\` than in \`DARK\``)
    }
  }

  const lines = [
    `// Generated by dowel's tools/build-tokens.mjs from theme.css. Do not edit.`,
    `//`,
    `// The dowel theme for ${name} (${colorName} ${accent}), for a product that`,
    `// draws without CSS. Include it where \`Color\` and \`const fn rgba\` are`,
    `// defined; https://lacodda.github.io/dowel/reference/palettes/ says how.`,
    '',
    `/// The \`dowel-ui\` release these values come from.`,
    `pub const VERSION: &str = ${JSON.stringify(version)};`,
    '',
    `/// The product, and the accent its palette is resolved on.`,
    `pub const PRODUCT: &str = ${JSON.stringify(name)};`,
    `pub const ACCENT: &str = ${JSON.stringify(accent)};`,
    '',
    `/// Every colour of the dowel theme on ${name}'s accent. One field per token.`,
    `#[derive(Clone, Copy, Debug, PartialEq)]`,
    `pub struct Palette {`,
    ...names.map((token) => `    pub ${field(token)}: Color,`),
    `}`,
  ]
  for (const { constantName, doc, colours } of modes) {
    lines.push('', `/// ${doc}`, `pub const ${constantName}: Palette = Palette {`)
    for (const [token, [r, g, b, a]] of colours) lines.push(`    ${field(token)}: rgba(${r}, ${g}, ${b}, ${a}),`)
    lines.push(`};`)
  }

  const module = (doc, modName, entries) => ['', `/// ${doc}`, `pub mod ${modName} {`, ...entries.map((entry) => `    ${entry}`), `}`]
  lines.push(
    ...module(
      'Corner radius, in pixels. `MD` is the control radius: inputs, buttons, list rows.',
      'radius',
      steps(tokens.radius).map(([step, { $value }]) => `pub const ${constant(step)}: f32 = ${float(pixels($value, `radius.${step}`))};`),
    ),
    ...module(
      'Type steps, in pixels: the size, and the line height it is set on.',
      'text',
      steps(tokens.typography).map(
        ([step, { $value }]) =>
          `pub const ${constant(step)}: (f32, f32) = (${float(pixels($value.fontSize, `typography.${step}`))}, ${float(pixels($value.lineHeight, `typography.${step}`))});`,
      ),
    ),
    ...module(
      'Font weights.',
      'font_weight',
      steps(tokens.fontWeight).map(([step, { $value }]) => `pub const ${constant(step)}: u16 = ${$value};`),
    ),
    ...module(
      "The weight of an icon's line, in the icon's own units (a 24-unit grid).",
      'icon',
      [`pub const STROKE: f32 = ${float(tokens.icon.stroke.$value)};`],
    ),
    ...module(
      'Motion. Cut to nothing when the system asks for reduced motion.',
      'duration',
      steps(tokens.duration).map(
        ([step, { $value }]) =>
          `pub const ${constant(step)}: std::time::Duration = std::time::Duration::from_millis(${milliseconds($value, `duration.${step}`)});`,
      ),
    ),
    ...module(
      'Easing curves, as the four control points of a cubic Bezier.',
      'easing',
      steps(tokens.easing).map(([step, { $value }]) => `pub const ${constant(step)}: [f32; 4] = [${$value.map(float).join(', ')}];`),
    ),
    ...module(
      'Stacking order: what covers what. Only the order means anything.',
      'layer',
      steps(tokens.layer).map(([step, { $value }]) => `pub const ${constant(step)}: i32 = ${$value};`),
    ),
  )
  return `${lines.join('\n')}\n`
}
